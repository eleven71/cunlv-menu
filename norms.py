def norm(name):
    # 阶段1：剥离括号备注，取基础名（"盐（腌肉用）"→"盐"）
    base = name.split('（')[0].split('(')[0].strip()
    # 阶段2：精确映射 + 整串子串兜底
    r = _norm_base(base)
    if r:
        return r
    # 阶段3：拆"或/斜杠/顿号"取首项后再映射（"黄酒或料酒"→"料酒"）
    for sep in ['或', '/', '、']:
        if sep in base:
            r = _norm_base(base.split(sep)[0].strip())
            if r:
                return r
    return base

# 非采购项判断（含子串匹配）
def is_non_shop(name):
    for k in NON_SHOP:
        if k in name:
            return True
    return False
